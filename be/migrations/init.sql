-- ============================================================================
-- 1. 用户表
-- ============================================================================
CREATE TABLE IF NOT EXISTS t_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash TEXT NOT NULL,
    email VARCHAR(255) NOT NULL,
    membership_plan_id BIGINT NOT NULL DEFAULT 1,
    status SMALLINT NOT NULL DEFAULT 1,
    deactivated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE t_users IS '用户表，保存注册用户和认证凭据';
COMMENT ON COLUMN t_users.id IS '用户 ID，自增主键';
COMMENT ON COLUMN t_users.username IS '登录用户名';
COMMENT ON COLUMN t_users.password_hash IS '密码哈希值，不保存明文密码';
COMMENT ON COLUMN t_users.email IS '用户邮箱，用于邮箱验证码登录和账号找回';
COMMENT ON COLUMN t_users.membership_plan_id IS '用户当前绑定的会员计划 ID，由应用层保证计划存在';
COMMENT ON COLUMN t_users.status IS '用户状态：1=正常，2=禁用，3=注销冷静期';
COMMENT ON COLUMN t_users.deactivated_at IS '用户进入注销冷静期的时间，超过 7 天后可由清理任务删除资产';
COMMENT ON COLUMN t_users.created_at IS '创建时间';
COMMENT ON COLUMN t_users.updated_at IS '更新时间';

ALTER TABLE t_users ADD CONSTRAINT t_users_email_key UNIQUE (email);

