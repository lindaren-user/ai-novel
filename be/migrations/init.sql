CREATE INDEX IF NOT EXISTS idx_t_user_feedbacks_user_created ON t_user_feedbacks(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_t_user_feedbacks_image_urls ON t_user_feedbacks USING GIN (image_urls);
CREATE INDEX IF NOT EXISTS idx_t_model_runs_user_start ON t_model_runs(user_id, start_time DESC);
CREATE INDEX IF NOT EXISTS idx_t_model_runs_scope ON t_model_runs(scope_type, scope_id);
