CREATE INDEX IF NOT EXISTS idx_t_membership_plans_features ON t_membership_plans USING GIN (features);
CREATE INDEX IF NOT EXISTS idx_t_users_membership_plan ON t_users(membership_plan_id);
CREATE INDEX IF NOT EXISTS idx_t_users_status ON t_users(status);
CREATE INDEX IF NOT EXISTS idx_t_users_status_deactivated_at ON t_users(status, deactivated_at);
