COMMENT ON COLUMN t_user_settings.updated_at IS '更新时间';

-- ============================================================================
-- 3. 模型配置表
-- ============================================================================
CREATE TABLE IF NOT EXISTS t_models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(100) NOT NULL,
    provider VARCHAR(40) NOT NULL DEFAULT 'custom_openai',
    model_id VARCHAR(120) NOT NULL DEFAULT '',
    api_url TEXT NOT NULL DEFAULT '',
    api_key TEXT NOT NULL DEFAULT '',
    top_p NUMERIC(4, 3) NOT NULL DEFAULT 0.9 CHECK (top_p >= 0 AND top_p <= 1),
    temperature NUMERIC(4, 2) NOT NULL DEFAULT 0.7 CHECK (temperature >= 0 AND temperature <= 2),
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, name)
);

COMMENT ON TABLE t_models IS '模型配置表，保存内置模型和用户自定义模型';
COMMENT ON COLUMN t_models.id IS '模型 ID，自增主键';
COMMENT ON COLUMN t_models.user_id IS '所属用户 ID，0 表示内置模型';
COMMENT ON COLUMN t_models.name IS '模型显示名称';
COMMENT ON COLUMN t_models.provider IS '模型厂商';
COMMENT ON COLUMN t_models.model_id IS '厂商侧模型 ID';
COMMENT ON COLUMN t_models.api_url IS '模型 API 地址';
COMMENT ON COLUMN t_models.api_key IS '模型 API Key';
COMMENT ON COLUMN t_models.top_p IS 'Top-p 参数';
COMMENT ON COLUMN t_models.temperature IS '温度参数';
COMMENT ON COLUMN t_models.status IS '模型状态：1=启用，2=禁用';
COMMENT ON COLUMN t_models.created_at IS '创建时间';
COMMENT ON COLUMN t_models.updated_at IS '更新时间';

