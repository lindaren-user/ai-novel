-- ============================================================================
-- 10. AI 运行记录表
-- ============================================================================
CREATE TABLE IF NOT EXISTS t_model_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    scope_type SMALLINT NOT NULL,
    scope_id BIGINT,
    model_id BIGINT NOT NULL DEFAULT 0,
    status SMALLINT NOT NULL DEFAULT 0,
    token_count BIGINT NOT NULL DEFAULT 0,
    finish_reason TEXT NOT NULL DEFAULT '',
    error_message TEXT NOT NULL DEFAULT '',
    start_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    end_time TIMESTAMPTZ
);

COMMENT ON TABLE t_model_runs IS 'AI 运行记录表，保存每次模型调用的运行元数据，避免污染对话消息表';
COMMENT ON COLUMN t_model_runs.id IS '运行记录 ID，自增主键';
COMMENT ON COLUMN t_model_runs.user_id IS '发起运行的用户 ID，由应用层保证用户存在';
COMMENT ON COLUMN t_model_runs.scope_type IS '运行范围类型：1=对话消息，2=新建小说设定生成，3=草稿润色，4=草稿校验';
COMMENT ON COLUMN t_model_runs.scope_id IS '运行范围对象 ID：消息为 t_chat_messages.id，新建小说设定生成为空，润色和校验为 t_chapter_contents.id';
COMMENT ON COLUMN t_model_runs.model_id IS '使用的模型配置 ID，对应 t_models.id，0 表示未解析到模型';
COMMENT ON COLUMN t_model_runs.status IS '运行状态：0=运行中，1=成功，2=失败，3=取消';
COMMENT ON COLUMN t_model_runs.token_count IS '模型返回的 token 消耗数，未返回时为 0';
COMMENT ON COLUMN t_model_runs.finish_reason IS '模型结束原因，未返回时为空字符串';
COMMENT ON COLUMN t_model_runs.error_message IS '失败时的错误摘要，成功时为空字符串';
COMMENT ON COLUMN t_model_runs.start_time IS '运行开始时间';
COMMENT ON COLUMN t_model_runs.end_time IS '运行结束时间，运行中为空';

